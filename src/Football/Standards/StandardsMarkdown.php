<?php

declare(strict_types=1);

namespace App\Football\Standards;

use App\Football\Data\RoleCatalog;

/**
 * Renders the derived standards as docs/standards.md: the full investigation, generated.
 *
 * @phpstan-import-type Standards from StandardsFile
 */
final class StandardsMarkdown
{
    private const METHODS = [
        'standards' => 'The standards: weight = link with winning × repeatability',
        'equal_measures' => 'The same measures, weighted equally',
        'all_candidates' => 'Every candidate statistic, weighted equally ("every good statistic counts")',
        'winning_only' => 'The same measures, weighted by link with winning only',
    ];

    /** @param Standards $standards */
    public function render(array $standards): string
    {
        [$first, $second] = $standards['seasons'];
        $label = static fn (string $code) => '20' . substr($code, 0, 2) . '/' . substr($code, 2, 2);
        $d = $standards['derivation'];

        $md = "# Positional standards ({$standards['id']})\n\n"
            . "Generated by `php bin/console app:standards:derive` from the {$label($first)} and {$label($second)} league seasons of the\n"
            . "Top-5 dataset; do not edit by hand. The frozen numbers are in `config/standards/{$standards['id']}.json`; the model\n"
            . "reads them from there. The explanation for readers is in [methodology.md](methodology.md).\n\n"
            . "## The question\n\n"
            . "For each role (striker, winger, attacking, central and defensive midfielder, full-back, centre-back,\n"
            . "goalkeeper): which statistics show that a player is good at his role, and how much should each count?\n"
            . "The answer is measured, not chosen. Football is won by goal difference, so a statistic counts for a role\n"
            . "when the players who do more of it play in teams that win, in both seasons, and when it is a stable trait\n"
            . "of the player rather than luck.\n\n"
            . "## Method\n\n"
            . sprintf("Players with %d+ league minutes in a season, compared within their role. Per role and statistic:\n\n", (int) $d['min_minutes'])
            . "1. **Measure**: per 90 minutes (counts) or as a success rate (successes / attempts). Failures (errors,\n"
            . "   lost duels, cards) count against the player.\n"
            . "2. **Small samples**: a value is pulled toward the role's average in proportion to how little it rests on.\n"
            . "   How strongly follows from the data: if a statistic over a typical sample of n̄ matches (or attempts)\n"
            . "   repeats between seasons with correlation ρ, a player's value keeps n / (n + k) of its distance from\n"
            . "   the average, with k = n̄ (1 − ρ) / ρ.\n"
            . "3. **Scale**: counts on a square-root scale (the standard variance-stabilising transform for counts), so\n"
            . "   a few extreme values do not dominate.\n"
            . "4. **Possession**: a team with the ball passes more; one without defends more. The part of the statistic\n"
            . "   that the team's possession explains (a linear fit within the role) is removed, and so is the part of\n"
            . "   the team's goal difference that its possession explains. Possession is estimated from passing.\n"
            . sprintf("5. **Link with winning**: the correlation between the statistic and the team's goal difference per match.\n   A statistic is **used** only when that link is positive and significant (one-sided 5%%, z = %.3f / √n)\n   in **each season on its own**: a link that does not replicate is likely chance.\n", $d['z_one_sided'])
            . "6. **Repeatability**: the correlation of the statistic for the same players in the same role in both seasons.\n"
            . sprintf("7. **Counted once**: used statistics that correlate %.1f or more (average linkage) form one **measure**: the\n   average of their standardised values.\n", $d['same_thing'])
            . "8. **Weight** of a measure = its link with winning × its repeatability, scaled so a role's weights add up to\n"
            . "   100%. A measure that goes with winning but barely repeats is mostly luck, and counts little.\n\n"
            . "Candidates are all statistics in the data whose direction is clear from their definition; the others are listed\n"
            . 'at the end with the reason. Coverage: a statistic must be known for '
            . sprintf("%d%% of a role's players.\n\n", (int) round($d['min_coverage'] * 100))
            . "The only fixed numbers above are statistical conventions (significance level, \"very strong\" correlation,\n"
            . "minimum minutes), the same for every role and statistic.\n\n";

        $md .= "## Validation\n\n"
            . "Standards derived from {$label($first)} alone (its team results decide; repeatability uses {$label($second)}'s\n"
            . "statistics, never its results) rate the {$label($first)} players. Two tests on {$label($second)}:\n\n"
            . "- **Team results**: a team's {$label($second)} goal difference against the average {$label($first)} rating of the players it\n"
            . "  fields in {$label($second)} (minutes-weighted; teams whose rated players played 20%+ of its minutes); also beyond its\n"
            . "  {$label($first)} goal difference.\n"
            . "- **Repeatability**: how alike the same players are rated in both seasons.\n\n"
            . "| Method | Team results r | Beyond last season's results | Teams | Repeatability r | Players |\n|---|---|---|---|---|---|\n";
        foreach ($standards['validation'] as $method => $v) {
            $md .= sprintf(
                "| %s | %s | %s | %d | %s | %d |\n",
                self::METHODS[$method] ?? $method,
                self::r($v['team_r']),
                self::r($v['team_r_beyond_previous']),
                $v['teams'],
                self::r($v['repeatability']),
                $v['players'],
            );
        }
        $md .= "\nWith about 80 teams a difference in r below 0.2 is within chance; the repeatability comparison, over\n"
            . "1,000+ players, is the sharper test.\n";

        foreach (RoleCatalog::ROLES as $role => $meta) {
            $standard = $standards['roles'][$role] ?? null;
            if ($standard === null) {
                continue;
            }
            $md .= sprintf(
                "\n## %s\n\n%d player seasons with %d+ minutes (%s), %d players in the role in both seasons.\n\n",
                ucfirst($meta['plural']),
                $standard['players'],
                (int) $d['min_minutes'],
                implode(' + ', array_map(static fn ($n, $code) => "{$n} in {$label((string) $code)}", $standard['seasons'], array_keys($standard['seasons']))),
                $standard['pairs'],
            );
            $name = strtolower($meta['label']);
            $md .= '### How ' . (in_array($name[0], ['a', 'e', 'i', 'o', 'u'], true) ? 'an' : 'a') . " {$name} earns points\n\n"
                . "| Weight | Measure | Link with winning | Repeatability |\n|---|---|---|---|\n";
            foreach ($standard['measures'] as $m) {
                $md .= sprintf("| %.0f%% | %s | %s | %s |\n", $m['weight'] * 100, $m['label'], self::r($m['relevance']), self::r($m['reliability']));
            }
            $md .= "\n### Every candidate statistic\n\n"
                . "| Statistic | Players | Link with winning ({$label($first)} / {$label($second)}) | Repeatability | Used | Why not |\n|---|---|---|---|---|---|\n";
            foreach ($standard['statistics'] as $s) {
                $md .= sprintf(
                    "| %s%s | %d | %s | %s | %s | %s |\n",
                    $s['label'],
                    $s['direction'] < 0 ? ' (counts against)' : '',
                    $s['players'],
                    $s['relevance'] === [] ? '–' : implode(' / ', array_map(self::r(...), $s['relevance'])),
                    self::r($s['reliability']),
                    $s['used'] ? 'yes' : '',
                    $s['reason'] ?? '',
                );
            }
            $used = array_filter($standard['statistics'], static fn (array $s) => $s['used']);
            if ($used !== []) {
                $md .= "\nHow the used statistics are prepared (k: pulled toward the average as if the player had k more\n"
                    . "matches or attempts at the average; possession: change per unit of possession share, on the statistic's\n"
                    . "scale, removed around the mean possession; proxy: scale of the SofaScore estimate used when Understat has\n"
                    . "no record of the player):\n\n| Statistic | k | Possession slope | Proxy scale |\n|---|---|---|---|\n";
                foreach ($used as $s) {
                    $md .= sprintf(
                        "| %s | %s | %s | %s |\n",
                        $s['label'],
                        $s['prior'] === null ? '–' : number_format((float) $s['prior'], 1),
                        $s['slope'] === null ? '–' : number_format((float) $s['slope'], 3),
                        ($s['proxy_scale'] ?? null) === null ? '–' : number_format((float) $s['proxy_scale'], 4),
                    );
                }
            }
        }

        $md .= "\n## Statistics in the data that are not candidates\n\n| Statistic | Why |\n|---|---|\n";
        foreach (StatisticCatalog::excluded() as $statistic => $reason) {
            $md .= "| {$statistic} | {$reason} |\n";
        }

        return $md;
    }

    private static function r(?float $r): string
    {
        return $r === null ? '–' : number_format($r, 2);
    }
}
