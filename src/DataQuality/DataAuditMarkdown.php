<?php

declare(strict_types=1);

namespace App\DataQuality;

use App\Entity\ImportBatch;
use App\Football\Assessment\AssessmentScope;
use App\Football\Data\Field;

/** Renders the DataAudit result as the Markdown data coverage report (docs/data-coverage.md). */
final class DataAuditMarkdown
{
    /** @param array<string, mixed> $audit */
    public function render(array $audit): string
    {
        /** @var AssessmentScope $scope */
        $scope = $audit['scope'];
        $out = [];
        $out[] = "# Data coverage report — season {$scope->season}";
        $out[] = '';
        $out[] = sprintf(
            '_Generated by `php bin/console app:data:audit` on %s. Do not edit by hand._',
            $audit['generated_at']->format('j M Y')
        );
        $out[] = '';
        $out[] = 'What the imported data can and cannot tell the model. Every number below is measured on the actual records.';
        $out[] = '';

        $out[] = '## 1. Assessment scope';
        $out[] = '';
        $out[] = sprintf('- **Season:** %s (period %s to %s).', $scope->season, $scope->periodFrom, $scope->periodTo);
        $out[] = sprintf('- **Included:** domestic league matches in %s, and the UEFA Champions League from the league phase on.', implode(', ', $scope->leagues));
        $out[] = '- **Excluded:** CL qualifying rounds, domestic cups, super cups, Club World Cup, international matches.';
        $out[] = '';

        $out[] = '## 2. Sources';
        $out[] = '';
        $out[] = '| Source | Dataset | Competitions | Records | Rejected | Version | Imported |';
        $out[] = '|---|---|---|---:|---:|---|---|';
        foreach ($audit['batches'] as $b) {
            /** @var ImportBatch $b */
            $out[] = sprintf(
                '| [%s](%s) | %s | %s | %s | %d | %s | %s (batch #%d) |',
                $b->getSource(),
                self::link($b->getSourceUrl()),
                $b->getDataset(),
                $b->getCompetitionCode(),
                number_format($b->getRecordCount()),
                $b->getRejectedCount(),
                $b->getSourceVersion() !== null ? '`' . substr($b->getSourceVersion(), 0, 10) . '`' : '–',
                $b->getImportedAt()->format('Y-m-d'),
                $b->getId(),
            );
        }
        $out[] = '';
        $l = $audit['league'];
        $out[] = sprintf(
            'League data: %s stint rows → **%s players** (%d transferred during the season), **%s with %d+ minutes** (%d goalkeepers).',
            number_format($l['stint_rows']),
            number_format($l['players']),
            $l['transferred'],
            number_format($l['regular']),
            DataAudit::LEAGUE_MIN_MINUTES,
            $l['regular_goalkeepers'],
        );
        $out[] = '';

        $out[] = '## 3. Coverage matrix';
        $out[] = '';
        $out[] = sprintf(
            '"Trusted" = the value exists and its provider covers the whole season and agrees with FBref (see section 4). League shares are over players with %d+ minutes (goalkeeping fields: goalkeepers only); CL over players with %d+ CL minutes.',
            DataAudit::LEAGUE_MIN_MINUTES,
            DataAudit::CL_MIN_MINUTES,
        );
        $out[] = '';
        $out[] = '| Statistic | Provider (league) | League present | League trusted | Partial | CL missing | Verdict | Note |';
        $out[] = '|---|---|---:|---:|---:|---:|---|---|';
        $category = null;
        foreach ($audit['fields'] as $row) {
            /** @var Field $field */
            $field = $row['field'];
            if ($field->category !== $category) {
                $category = $field->category;
                $out[] = "| **{$category}** | | | | | | | |";
            }
            $out[] = sprintf(
                '| %s | %s | %s | %s | %s | %s | %s | %s |',
                $field->label,
                $field->origin->value . ($field->leagueColumn !== null ? " `{$field->leagueColumn}`" : ''),
                self::pct($row['present_pct']),
                self::pct($row['trusted_pct']),
                $row['partial'] ?: '',
                $row['cl'] === null ? '–' : sprintf('%d / %d', $row['cl']['missing'], $row['cl']['population']),
                $row['verdict'],
                $field->note ?? '',
            );
        }
        $out[] = '';
        $out[] = '**Not available from any free source:**';
        $out[] = '';
        foreach ($audit['unavailable'] as $label => $reason) {
            $out[] = "- {$label}: {$reason}.";
        }
        $out[] = '';

        $out[] = '## 4. Provider consistency (league data)';
        $out[] = '';
        $out[] = 'FBref is the reference for playing time. For every player, the Understat and SofaScore records are checked against it:';
        $out[] = '';
        $out[] = sprintf(
            '- **ok**: minutes agree within %d%% (at least %d minutes), and SofaScore goals within %d of FBref.',
            OriginConsistency::MINUTES_TOLERANCE * 100,
            OriginConsistency::MINUTES_TOLERANCE_ABSOLUTE,
            OriginConsistency::GOALS_TOLERANCE,
        );
        $out[] = '- **partial**: the player changed leagues and the provider only has one of them. Its numbers are real but cover fewer minutes.';
        $out[] = '- **suspect**: disagrees with FBref for a single club: most likely another player\'s record was merged in.';
        $out[] = '- **missing**: the provider has no record for the player.';
        $out[] = '';
        $out[] = sprintf('| Provider | ok | partial | suspect | missing | (all players: ok / partial / suspect / missing) |');
        $out[] = '|---|---:|---:|---:|---:|---|';
        foreach ($audit['origins'] as $origin => $row) {
            $r = $row['regular_counts'];
            $a = $row['counts'];
            $out[] = sprintf(
                '| %s (%d+ min) | %d | %d | %d | %d | %d / %d / %d / %d |',
                $origin, DataAudit::LEAGUE_MIN_MINUTES, $r['ok'], $r['partial'], $r['suspect'], $r['missing'],
                $a['ok'], $a['partial'], $a['suspect'], $a['missing'],
            );
        }
        $out[] = '';
        foreach ($audit['origins'] as $origin => $row) {
            foreach (['partial', 'suspect', 'missing'] as $status) {
                $examples = $row['examples'][$status];
                if ($examples === []) {
                    continue;
                }
                $out[] = sprintf('**%s — %s** (most minutes first):', $origin, $status);
                $out[] = '';
                foreach ($examples as $e) {
                    $out[] = sprintf('- %s (%s, %s min)%s', $e['player'], $e['teams'], number_format($e['minutes']), $e['reason'] && $status !== 'missing' ? ': ' . $e['reason'] : '');
                }
                $out[] = '';
            }
        }

        $c = $audit['cl'];
        $out[] = '## 5. Champions League';
        $out[] = '';
        $out[] = sprintf(
            '- **%d players** from %d clubs (%d with %d+ minutes), %d goals in total.',
            $c['players'], $c['teams'], $c['regular'], DataAudit::CL_MIN_MINUTES, $c['goals'],
        );
        $methods = implode(', ', array_map(static fn ($m, $n) => "{$n} by {$m}", array_keys($c['methods']), $c['methods']));
        $out[] = sprintf(
            '- **Link to league data:** of %d players at the %d top-5 clubs, %d are linked (%s); %d remain unlinked. Rules: `src/DataImport/Identity/ClPlayerMatcher.php`, manual links: `config/identity/players.yaml`.',
            $c['top5_players'], $c['top5_teams'], array_sum($c['methods']), $methods, count($c['unlinked_at_top5']),
        );
        $out[] = sprintf(
            '- %d players at %d clubs outside the top-5 leagues (%s). %d of them also played in a top-5 league this season (transfer); the rest have CL data only and cannot be ranked on a full season.',
            $c['other_players'], count($c['other_teams']), implode(', ', $c['other_teams']), $c['other_linked'],
        );
        $out[] = sprintf(
            '- xG is empty for %d players without a shot (= 0 xG, safe to treat as zero) and for %d players who did shoot (unknown).',
            $c['xg_null_no_shots'], $c['xg_null_with_shots'],
        );
        $out[] = '';
        if ($c['linked_by_name'] !== []) {
            $out[] = 'Linked without an exact id (their league SofaScore id is missing, shared or suspect). Check these:';
            $out[] = '';
            foreach ($c['linked_by_name'] as $p) {
                $out[] = sprintf('- %s (%s, %d CL min) → %s [%s]', $p['player'], $p['team'], $p['minutes'], $p['match'], $p['method']);
            }
            $out[] = '';
        }
        if ($c['unlinked_at_top5'] !== []) {
            $out[] = 'Still unlinked at top-5 clubs (most CL minutes first): players without league minutes in the dataset.';
            $out[] = '';
            foreach (array_slice($c['unlinked_at_top5'], 0, 15) as $p) {
                $out[] = sprintf('- %s (%s, %d CL min)', $p['player'], $p['team'], $p['minutes']);
            }
            $out[] = '';
        }

        if ($audit['fotmob'] !== null) {
            $f = $audit['fotmob'];
            $out[] = '### Cross-check: SofaScore vs FotMob';
            $out[] = '';
            $out[] = sprintf(
                'Totals: SofaScore %s minutes, %d goals, %d assists; FotMob %s minutes, %d goals, %d assists.',
                number_format($c['minutes']), $c['goals'], $c['assists'],
                number_format($f['totals']['minutes']), $f['totals']['goals'], $f['totals']['assists'],
            );
            $out[] = '';
            $out[] = sprintf(
                '%d players matched on name (%d ambiguous, %d not found). Minutes agree within tolerance for **%d** (exactly for %d), goals for **%d**, assists for **%d**.',
                $f['matched'], $f['ambiguous'], $f['unmatched'], $f['minutes_ok'], $f['minutes_exact'], $f['goals_ok'], $f['assists_ok'],
            );
            $out[] = '';
            if ($f['disagreements'] !== []) {
                $out[] = sprintf('Largest of %d disagreements:', $f['disagreement_count']);
                $out[] = '';
                $out[] = '| Player | Club | SofaScore | FotMob |';
                $out[] = '|---|---|---|---|';
                foreach ($f['disagreements'] as $d) {
                    $out[] = sprintf('| %s | %s | %s | %s |', $d['player'], $d['team'], $d['sofascore'], $d['fotmob']);
                }
                $out[] = '';
            }
        }

        $out[] = '## 6. Rules for the model';
        $out[] = '';
        $out[] = '1. **Missing is never zero.** A missing value is excluded from a comparison, and the score shows reduced confidence. Exception: SofaScore CL xG/xA is empty when there is nothing to measure (no shots), which is a real zero.';
        $out[] = '2. **Per-90 uses the provider\'s own minutes.** Understat stats are divided by Understat minutes and SofaScore stats by SofaScore minutes, never by FBref minutes.';
        $out[] = '3. **Partial providers** (transfers between leagues) are used for per-90 rates only, and flagged. Season totals come from FBref, which covers every club.';
        $out[] = '4. **Suspect records are treated as missing.**';
        $out[] = '5. **Penalties:** FBref goals include penalties. Non-penalty goals = goals − SofaScore penalty goals, only when SofaScore is trusted for the player.';
        $out[] = '6. **League and CL xG come from different models** (Understat vs SofaScore). Compare each within its competition; never add them.';
        $out[] = '7. **League and CL stay separate** until the competition-context phase decides how to combine them; a CL goal is never counted in the league totals.';
        $out[] = '';

        return implode("\n", $out);
    }

    private static function pct(?float $value): string
    {
        return $value === null ? '–' : $value . '%';
    }

    private static function link(string $url): string
    {
        return str_replace(['(', ')', ' '], ['%28', '%29', '%20'], strtok($url, '?') ?: $url);
    }
}
